#!/usr/bin/env python3
"""Generates src/editor/ui/icons.hpp from the vendored Lucide icon font.

    scripts/gen_editor_icons.py            # rewrite the header
    scripts/gen_editor_icons.py --check    # exit 1 if the header is stale

The editor merges assets/fonts/lucide/lucide.ttf into its UI font. Each icon
the editor uses is listed in ICONS below (Lucide names, see
https://lucide.dev/icons); the header maps it to a UTF-8 string constant
(`engine::editor::icon::play`) via assets/fonts/lucide/codepoints.json, plus a
table the font loader turns into glyph ranges (only listed icons are baked
into the atlas). To add an icon: append its Lucide name here and rerun.
"""

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CODEPOINTS = ROOT / "assets" / "fonts" / "lucide" / "codepoints.json"
HEADER = ROOT / "src" / "editor" / "ui" / "icons.hpp"

ICONS = """
activity app-window arrow-down arrow-up atom audio-lines box boxes braces brain brush bug
camera check chevron-down chevron-right chevrons-up-down circle-alert circle-check
circle-dot circle-help circle-x clapperboard clipboard-paste clock-3 cloud code command
compass copy cpu crosshair cuboid ear ellipsis-vertical eye eye-off file file-audio
file-box file-code file-image file-json file-plus file-text film filter flame folder
folder-open folder-tree footprints gamepad-2 gauge git-fork globe grid-3x3 hand hash house
image info keyboard layers layout-dashboard layout-grid leaf lightbulb link list list-tree
lock log-out magnet map-pin maximize-2 monitor moon mountain mouse-pointer-2 move
network orbit package palette panel-bottom panel-left panel-right pause person-standing
pin play plug plus radio-tower redo-2 refresh-cw rotate-3d rotate-ccw route ruler save
scale-3d scan-eye scroll-text search settings settings-2 shapes shield sliders-horizontal
sparkles sprout square step-forward sun sun-medium tag terminal timer trash-2
tree-pine trees triangle-alert type undo-2 video volume-2 waves wifi wind workflow wrench
x zap
""".split()


def utf8_escape(codepoint: int) -> str:
    return "".join(f"\\x{b:02x}" for b in chr(codepoint).encode("utf-8"))


def render(codepoints: dict) -> str:
    missing = [name for name in ICONS if name not in codepoints]
    if missing:
        sys.exit(f"gen_editor_icons: not in {CODEPOINTS.name}: {', '.join(missing)}")
    if len(set(ICONS)) != len(ICONS):
        sys.exit("gen_editor_icons: duplicate names in ICONS")
    entries = sorted(ICONS)
    lines = [
        "#pragma once",
        "",
        "// GENERATED by scripts/gen_editor_icons.py from",
        "// assets/fonts/lucide/codepoints.json - do not edit; add icons to the",
        "// script's ICONS list and rerun it. Lucide is ISC-licensed",
        "// (assets/fonts/lucide/LICENSE.txt).",
        "//",
        "// Each constant is the icon's UTF-8 string, for concatenation with labels",
        "// (ui::label(icon::play, \"Play\")) once the icon font is merged into the",
        "// UI font (ui/fonts.hpp).",
        "",
        "#include <cstddef>",
        "#include <string_view>",
        "",
        "namespace engine::editor::icon {",
        "",
    ]
    for name in entries:
        cp = codepoints[name]
        ident = name.replace("-", "_")
        lines.append(f'inline constexpr char {ident}[] = "{utf8_escape(cp)}"; // U+{cp:04X} {name}')
    lines += [
        "",
        "struct IconEntry {",
        "    std::string_view name;      // Lucide name",
        "    char32_t         codepoint; // Unicode private-use code point",
        "    const char*      utf8;      // the constant above",
        "};",
        "",
        "// Every icon above, sorted by name.",
        "inline constexpr IconEntry k_icons[] = {",
    ]
    for name in entries:
        lines.append(f'    {{"{name}", 0x{codepoints[name]:04X}, {name.replace("-", "_")}}},')
    lines += [
        "};",
        "inline constexpr std::size_t k_icon_count = sizeof(k_icons) / sizeof(k_icons[0]);",
        "",
        "} // namespace engine::editor::icon",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    codepoints = json.loads(CODEPOINTS.read_text(encoding="utf-8"))
    text = render(codepoints)
    if "--check" in sys.argv[1:]:
        current = HEADER.read_text(encoding="utf-8") if HEADER.exists() else ""
        if current != text:
            print(f"{HEADER.relative_to(ROOT)} is stale; run scripts/gen_editor_icons.py")
            return 1
        return 0
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text(text, encoding="utf-8")
    print(f"wrote {HEADER.relative_to(ROOT)} ({len(ICONS)} icons)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
